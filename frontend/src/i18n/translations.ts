const isTranslationNode = (value: TranslationValue | undefined): value is TranslationNode =>
  typeof value === 'object' && value !== null;

export const isSupportedLanguage = (
  language: string | null | undefined,
): language is AppLanguage =>
  typeof language === 'string' &&
  (SUPPORTED_LANGUAGES as readonly string[]).includes(language);

export const resolveLanguage = (
  language: string | null | undefined,
): AppLanguage => (isSupportedLanguage(language) ? language : DEFAULT_LANGUAGE);

export const getNestedTranslation = (
  node: TranslationNode,
  key: string,
): string | undefined => {
  const parts = key.split('.');
  let current: TranslationValue | undefined = node;

  for (const part of parts) {
    if (!isTranslationNode(current)) {
      return undefined;
    }

    current = current[part];
  }

  return typeof current === 'string' ? current : undefined;
};

export const getTranslationValue = (
  language: string | null | undefined,
  key: string,
): string | undefined => {
  const resolvedLanguage = resolveLanguage(language);

  return (
    getNestedTranslation(TRANSLATIONS[resolvedLanguage], key) ??
    getNestedTranslation(TRANSLATIONS[DEFAULT_LANGUAGE], key)
  );
};

export const getOpenGraphLocale = (
  language: string | null | undefined,
): string => OPEN_GRAPH_LOCALE_BY_LANGUAGE[resolveLanguage(language)];
